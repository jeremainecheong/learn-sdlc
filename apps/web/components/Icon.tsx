export function Icon({ name, size = 18, strokeWidth = 1.7, className = '', title }: {
  name: IconName; size?: number; strokeWidth?: number; className?: string; title?: string;
}) {
  const Glyph = ICONS[(ALIAS[name] ?? name) as Canonical] ?? FileText;
  return <Glyph size={size} strokeWidth={strokeWidth} className={`shrink-0 ${className}`}
    role={title ? 'img' : undefined} aria-label={title} aria-hidden={title ? undefined : true} />;
}
