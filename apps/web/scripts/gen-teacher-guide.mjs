#!/usr/bin/env node
/**
 * Writes lib/teacher-guide-doc.generated.ts from
 * docs/teacher-project-upload.md, so /teacher/guide draws the same words the
 * docs file holds. `--check` writes nothing and exits 1 when the module is not
 * what this script would write (the drift test).
 *
 * What it does to the text, deterministically:
 * - line endings become \n;
 * - a link to another document (`[text](other.md#…)`) becomes its text, since
 *   the in-app page has no route to that file; in-page `#…` links stay;
 * - the text is cut at each `## ` heading outside a code fence: what comes
 *   before the first is the preamble, and each section keeps its heading and
 *   takes GitHub's slug of it as its id, so the document's own `#…` links land;
 * - a trailing `---` rule is dropped from each part.
 * It refuses (exit 2) a document that would put a quoted project slug in the
 * web tree, which the codebase guard (test/useProject.test.ts) forbids.
 *
 * Run: npm run gen:teacher-guide -w @learnsdlc/web (check:teacher-guide for
 * --check), or node apps/web/scripts/gen-teacher-guide.mjs [--check] [--doc <path>] [--out <path>]
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = resolve(fileURLToPath(new URL('..', import.meta.url)));
const args = process.argv.slice(2);
const flag = (name) => {
  const at = args.indexOf(name);
  return at >= 0 ? args[at + 1] : undefined;
};
const check = args.includes('--check');
const DOC = resolve(flag('--doc') ?? join(HERE, '..', '..', 'docs', 'teacher-project-upload.md'));
const OUT = resolve(flag('--out') ?? join(HERE, 'lib', 'teacher-guide-doc.generated.ts'));

export function slug(title) {
  return title
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

/**
 * The document as the guide page's sections. A link to another file the app
 * has no route to keeps its words only, and a bare file name reads as words
 * ("authoring-format.md" reads "the authoring format").
 */
export function render(source) {
  const text = source.replace(/\r\n?/g, '\n').replace(/\[([^\]]+)\]\((?!#|https?:)[^)\s]+\)/g, (_, words) =>
    /^[a-z0-9-]+\.md$/.test(words) ? `the ${words.slice(0, -3).replace(/-/g, ' ')}` : words,
  );
  const parts = [{ title: null, lines: [] }];
  let fenced = false;
  for (const line of text.split('\n')) {
    if (/^(```|~~~)/.test(line)) fenced = !fenced;
    if (!fenced && /^## /.test(line)) parts.push({ title: line.slice(3).trim(), lines: [] });
    parts[parts.length - 1].lines.push(line);
  }
  const tidy = (lines) => lines.join('\n').replace(/(\n\s*---\s*)+\s*$/, '').trim();
  const seen = new Map();
  const sections = parts.slice(1).map((part) => {
    const base = slug(part.title);
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    return { id: n === 0 ? base : `${base}-${n}`, title: part.title, markdown: tidy(part.lines) };
  });
  const digest = createHash('sha256').update(source).digest('hex');
  return [
    '// GENERATED by apps/web/scripts/gen-teacher-guide.mjs from docs/teacher-project-upload.md.',
    '// Do not edit by hand: run `node apps/web/scripts/gen-teacher-guide.mjs`; `--check` proves it current.',
    '',
    'export interface TeacherGuideSection {',
    '  /** GitHub\'s slug of the heading, so the document\'s own links land. */',
    '  id: string;',
    '  title: string;',
    '  /** The section, its heading included. */',
    '  markdown: string;',
    '}',
    '',
    `export const TEACHER_GUIDE_SOURCE_SHA256 = ${JSON.stringify(digest)};`,
    '',
    `export const TEACHER_GUIDE_PREAMBLE: string = ${JSON.stringify(tidy(parts[0].lines))};`,
    '',
    'export const TEACHER_GUIDE_SECTIONS: readonly TeacherGuideSection[] = [',
    ...sections.map((one) => `  { id: ${JSON.stringify(one.id)}, title: ${JSON.stringify(one.title)}, markdown: ${JSON.stringify(one.markdown)} },`),
    '];',
    '',
  ].join('\n');
}

const out = render(readFileSync(DOC, 'utf8'));
if (/(['"`])tasktrackr\1/.test(out) || /project=tasktrackr/.test(out)) {
  console.error('The document would put a quoted project slug in the web tree, which the codebase guard forbids. Nothing was written.');
  process.exit(2);
}
if (check) {
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (now !== out) {
    console.error(`${OUT} is not what the document gives. Run node apps/web/scripts/gen-teacher-guide.mjs to write it.`);
    process.exit(1);
  }
  console.log('The teacher guide module is current.');
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote ${OUT}.`);
}
