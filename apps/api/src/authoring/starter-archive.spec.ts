/** The starter read the way the upload door reads it, from the archive the route serves. */
function loadedFromArchive(bytes: Buffer): { source: MemoryPackSource; names: string[] } {
  const entries = readZip(bytes, zipLimits(COHORT_IMPORT_MAX_BYTES));
  const root = packRootOf(entries);
  const source = new MemoryPackSource(entries, 'upload', root);
  const prefix = root ? `${root}/` : '';
  const names = entries.filter((entry) => entry.name.startsWith(prefix)).map((entry) => entry.name.slice(prefix.length)).filter(Boolean);
  return { source, names };
}

