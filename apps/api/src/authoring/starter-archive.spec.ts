describe('the generated module is the export writer over the fixture', () => {
  it('holds, per archive, exactly storedZipOf(root, the pack files) and its sha256', () => {
    for (const name of STARTER_ARCHIVE_NAMES) {
      const files = new Map(packFilesOf(path.join(PACKS, name)).map((file) => [file.name, file.data] as const));
      const want = storedZipOf(archiveRootOf(name), files);
      const record = STARTER_ARCHIVE_RECORDS[name];
      const held = Buffer.from(record.base64, 'base64');
      expect(held.equals(want)).toBe(true);
      expect(record.size).toBe(want.length);
      expect(record.sha256).toBe(sha(want));
      expect(record.filename).toBe(`learnsdlc-${name}.zip`);
    }
  });

  it('--check is green against the generated module, and writes nothing', () => {
    const generated = path.join(__dirname, 'starter-archive.generated.ts');
    const before = fs.readFileSync(generated);
    const said: string[] = [];
    expect(generator(['--check'], (line) => said.push(line))).toBe(0);
    expect(said.join('')).toMatch(/match/);
    expect(fs.readFileSync(generated).equals(before)).toBe(true);
  });

  it('--check fails on a one-byte drift of the generated module', () => {
    const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'starter-archive-'));
    try {
      const text = fs.readFileSync(path.join(__dirname, 'starter-archive.generated.ts'), 'utf-8');
      // one base64 character of the starter's first data line, swapped for another
      const at = text.indexOf("base64: [\n      '") + "base64: [\n      '".length + 40;
      const drifted = `${text.slice(0, at)}${text[at] === 'A' ? 'B' : 'A'}${text.slice(at + 1)}`;
      expect(drifted.length).toBe(text.length);
      const file = path.join(scratch, 'starter-archive.generated.ts');
      fs.writeFileSync(file, drifted);
      expect(generator(['--check', '--generated', file], () => undefined)).toBe(1);
      fs.writeFileSync(file, text);
      expect(generator(['--check', '--generated', file], () => undefined)).toBe(0);
    } finally {
      fs.rmSync(scratch, { recursive: true, force: true });
    }
  });

  it('--check fails on a one-byte drift of the fixture', () => {
    const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'starter-archive-'));
    try {
      fs.cpSync(path.join(PACKS, 'starter'), path.join(scratch, 'starter'), { recursive: true });
      fs.cpSync(path.join(PACKS, 'shelf'), path.join(scratch, 'shelf'), { recursive: true });
      const generated = path.join(__dirname, 'starter-archive.generated.ts');
      expect(generator(['--check', '--fixtures', scratch, '--generated', generated], () => undefined)).toBe(0);
      const target = path.join(scratch, 'starter', 'START-HERE.md');
      const bytes = fs.readFileSync(target);
      bytes[0] = bytes[0] ^ 0x01;
      fs.writeFileSync(target, bytes);
      expect(generator(['--check', '--fixtures', scratch, '--generated', generated], () => undefined)).toBe(1);
    } finally {
      fs.rmSync(scratch, { recursive: true, force: true });
    }
  });

  it('renders the same text twice (no clock, no machine path)', () => {
    const one = renderStarterArchiveModule([archiveOf('starter'), archiveOf('shelf')]);
    const two = renderStarterArchiveModule([archiveOf('starter'), archiveOf('shelf')]);
    expect(one).toBe(two);
    expect(one).not.toContain(API_DIR);
    expect(one).not.toMatch(/\b20\d\d-\d\d-\d\dT/);
  });

  it('refuses bad usage with 3 and a missing pack with 1', () => {
    expect(generator([], () => undefined)).toBe(3);
    expect(generator(['--write', '--check'], () => undefined)).toBe(3);
    expect(generator(['--check', '--fixtures'], () => undefined)).toBe(3);
    const empty = fs.mkdtempSync(path.join(os.tmpdir(), 'starter-archive-'));
    try {
      expect(generator(['--check', '--fixtures', empty], () => undefined)).toBe(1);
    } finally {
      fs.rmSync(empty, { recursive: true, force: true });
    }
  });
});

describe('the server helper: starterArchive(name, audit)', () => {
  it('serves each archive as the generated bytes, with its filename and sha256, after one audit call', async () => {
    for (const name of ['starter', 'shelf'] as const) {
      const calls: StarterArchiveDownload[] = [];
      const got = await starterArchive(name, (download) => {
        calls.push(download);
      });
      const record = STARTER_ARCHIVE_RECORDS[name];
      expect(got.bytes.equals(Buffer.from(record.base64, 'base64'))).toBe(true);
      expect(got.filename).toBe(record.filename);
      expect(got.sha256).toBe(sha(got.bytes));
      expect(Object.keys(got).sort()).toEqual(['bytes', 'filename', 'sha256']);
      // one row's worth of facts, and never a byte of the archive
      expect(calls).toEqual([{ name, filename: record.filename, size: record.size, sha256: record.sha256 }]);
    }
  });

  it('awaits the audit before it hands the bytes over, and a failed audit hands over nothing', async () => {
    const order: string[] = [];
    const got = await starterArchive('starter', async () => {
      await new Promise((resolve) => setTimeout(resolve, 5));
      order.push('audited');
    });
    order.push('served');
    expect(order).toEqual(['audited', 'served']);
    expect(got.bytes.length).toBeGreaterThan(0);
    await expect(
      starterArchive('starter', () => {
        throw new Error('audit write failed');
      }),
    ).rejects.toThrow('audit write failed');
  });

  it('refuses an unknown name with a 404 that echoes nothing, and never calls the audit', async () => {
    for (const bad of ['', 'Starter', 'tasktrackr', '../shelf', 'shelf.zip', '__proto__', 'constructor', 'toString']) {
      let audited = 0;
      const error = await starterArchive(bad, () => {
        audited += 1;
      }).catch((caught: unknown) => caught);
      expect(error).toBeInstanceOf(HttpException);
      expect((error as HttpException).getStatus()).toBe(404);
      if (bad) expect(JSON.stringify((error as HttpException).getResponse())).not.toContain(bad);
      expect(audited).toBe(0);
      expect(isStarterArchiveName(bad)).toBe(false);
    }
    expect(isStarterArchiveName('starter')).toBe(true);
    expect(isStarterArchiveName('shelf')).toBe(true);
  });

  it('hands every caller its own copy, so one caller cannot change the next download', async () => {
    const first = await starterArchive('shelf', () => undefined);
    first.bytes.fill(0);
    const second = await starterArchive('shelf', () => undefined);
    expect(second.sha256).toBe(sha(second.bytes));
    expect(second.bytes.equals(Buffer.from(STARTER_ARCHIVE_RECORDS.shelf.base64, 'base64'))).toBe(true);
  });

  it('names the two archives the generated module records, in one order', () => {
    // the server serves the shared contract's list, and the generated module records exactly it
    expect([...STARTER_ARCHIVE_NAMES]).toEqual(['starter', 'shelf']);
    expect(Object.keys(STARTER_ARCHIVE_RECORDS)).toEqual([...STARTER_ARCHIVE_NAMES]);
  });

  it('imports nothing from test/ (the build boundary), and the generated module imports nothing at all', () => {
    const helper = fs.readFileSync(path.join(__dirname, 'starter-archive.ts'), 'utf-8');
    const generated = fs.readFileSync(path.join(__dirname, 'starter-archive.generated.ts'), 'utf-8');
    expect(helper).not.toMatch(/from\s+['"][^'"]*\/test\//);
    expect(generated).not.toMatch(/^\s*import\s/m);
    expect(generated).not.toMatch(/require\s*\(/);
  });
});

