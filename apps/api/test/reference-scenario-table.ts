import type { ContentService } from '../src/content/content.service';
import {
  applicationDigest,
  elementDigests,
  scenarioDigest,
} from '../src/content/reference-content';
import type { ReferenceScenarioRow } from '../src/content/reference-scenarios';

/**
 * The rows of `src/content/reference-scenarios.ts`, recomputed from the pack on
 * disk: the scenario anchor.
 *
 * Per **written** phase of the reference pack: the scenario digest, the
 * intro, the interview (where the phase holds one) and every read-only file
 * by path. Per **executable** phase: the intro (the intro door is open on all
 * six phases) and one application digest. The CLI writes the table
 * from these rows; the drift spec holds the committed table to them.
 */
export const SCENARIO_PACK = 'tasktrackr';

const EXECUTABLE = new Set(['code', 'tests', 'config']);

export function recordReferenceScenarioRows(content: ContentService): ReferenceScenarioRow[] {
  const project = content.getProject(SCENARIO_PACK);
  const rows: ReferenceScenarioRow[] = [];
  const row = (phaseKey: string, grain: ReferenceScenarioRow['grain'], key: string, digest: string): void => {
    rows.push({ pack: SCENARIO_PACK, version: project.version, phaseKey, grain, key, digest });
  };
  for (const phase of project.phases) {
    const elements = elementDigests(phase);
    row(phase.key, 'intro', '', elements.intro);
    if (EXECUTABLE.has(phase.checks.kind)) {
      row(phase.key, 'application', '', applicationDigest(phase));
      continue;
    }
    row(phase.key, 'scenario', '', scenarioDigest(phase));
    if (elements.interview !== null) row(phase.key, 'interview', '', elements.interview);
    for (const [at, sha] of Object.entries(elements.files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      row(phase.key, 'file', at, sha);
    }
  }
  return rows;
}

/**
 * The committed table, rows of other versions kept (a pack bump appends its
 * rows; 2.0.1's stay, because a copy of an older version is still the
 * reference's content), the current version's replaced, in a stable order.
 */
export function mergeReferenceScenarioRows(
  held: readonly ReferenceScenarioRow[],
  fresh: readonly ReferenceScenarioRow[],
): ReferenceScenarioRow[] {
  const current = new Set(fresh.map((one) => `${one.pack}@${one.version}`));
  return [...held.filter((one) => !current.has(`${one.pack}@${one.version}`)), ...fresh];
}

export function renderReferenceScenariosModule(rows: readonly ReferenceScenarioRow[]): string {
  const body = rows
    .map(
      (one) =>
        `  { pack: '${one.pack}', version: '${one.version}', phaseKey: '${one.phaseKey}', grain: '${one.grain}', key: ${JSON.stringify(one.key)}, digest: '${one.digest}' },`,
    )
    .join('\n');
  return `/**
 * GENERATED by \`apps/api/test/cli/reference-scenarios.ts\`: do not edit by hand.
 *
 * The digests of the reference project's written scenario.
 * \`reference-content.ts\` reads them: a written phase is the reference's only
 * when its written task anchor (\`reference-anchors.ts\`) **and** its scenario
 * digest are recorded, and provenance marks each intro, interview, read-only
 * file and application by whether its digest is here. A pack bump appends its
 * rows and keeps the old ones; the drift spec fails until the new rows are
 * recorded on purpose.
 *
 * This is the only runtime file of the scenario machinery's table, and it
 * imports nothing: the recorder lives under \`test/\` and never ships.
 */
export interface ReferenceScenarioRow {
  readonly pack: string;
  readonly version: string;
  readonly phaseKey: string;
  readonly grain: 'scenario' | 'intro' | 'interview' | 'file' | 'application';
  /** The file's path for a \`file\` row; empty for every other grain. */
  readonly key: string;
  readonly digest: string;
}

export const REFERENCE_SCENARIOS: readonly ReferenceScenarioRow[] = [
${body}
];
`;
}
