import 'reflect-metadata';
import * as fs from 'fs';
import * as path from 'path';
import { readSharedFromSource } from './shared-from-source';
import type * as Table from '../reference-anchor-table';

/**
 * Record the byte anchors of TaskTrackr's written tasks and phases into
 * `apps/api/src/assistant/reference-anchors.ts`, which reviewer scoping reads.
 *
 *   npx ts-node --project apps/api/tsconfig.json apps/api/test/cli/reference-anchors.ts [--check]
 *
 * It lives under `test/`: a tool that writes source must not ship
 * in the image, and a `src/` file importing `test/` stops `npm run build`. The
 * generated table is the only runtime file, and it imports nothing.
 *
 * It keeps every row of another pack version and replaces the current
 * version's (2.0.1's rows stay when the pack moves on). Recording is a
 * deliberate act (a pack bump, declared in the change that makes it) and
 * never the fix for a failing step.
 *
 * Exit codes: 0 written (or matches under --check), 1 the pack failed to load
 * or the table differs, 3 bad usage.
 *
 * The executable phases:
 *
 *   ... reference-anchors.ts --exec [--check] [--root <pack dir>]
 *
 * `--exec` records the `exec` anchors of the pack's **executable** phases
 * (`code`, `tests`, `config`) into their own generated file,
 * `apps/api/src/assistant/reference-exec-anchors.ts`, so `REFERENCE_ANCHORS`
 * and the plain `--check` stay at the four written rows, byte for byte.
 * `--root` names the pack directory the rows are recorded from (default
 * `content/tasktrackr`); each row carries the pack's own version: 2.0.1 for
 * TaskTrackr's rows, and a later version's rows are appended beside it,
 * never written over it. The exec table imports nothing; if it does not exist
 * yet, `--exec` (not `--check`) writes it empty and runs itself once more, in
 * a fresh process: the resolver that computes the anchors imports the table,
 * and this process's compiler has already seen it missing.
 */

const TABLE = path.resolve(__dirname, '..', '..', 'src', 'assistant', 'reference-anchors.ts');
const EXEC_TABLE = path.resolve(__dirname, '..', '..', 'src', 'assistant', 'reference-exec-anchors.ts');
const DEFAULT_ROOT = path.resolve(__dirname, '..', '..', '..', '..', 'content', 'tasktrackr');

const USAGE = `usage: ts-node test/cli/reference-anchors.ts [--exec] [--check] [--root <pack dir>]

  --check   compare against the committed table and write nothing
  --exec    the executable phases' exec anchors, in reference-exec-anchors.ts
  --root    the pack directory to record from (default content/tasktrackr)
  --help    print this
`;

/** One row of the generated `reference-exec-anchors.ts`. */
export interface ExecAnchorRow {
  readonly anchor: string;
  readonly grain: 'exec';
  readonly pack: string;
  readonly version: string;
  readonly phaseKey: string;
}

const EXECUTABLE_KINDS: readonly string[] = ['code', 'tests', 'config'];
/** The one pack whose rows these tables hold (the written table's `ANCHORED_PACK`). */
const REFERENCE_PACK = 'tasktrackr';

/**
 * The exec rows of one pack, recomputed from its bytes: one per executable
 * phase, over the phase's sole work task (an executable phase of the pack has
 * exactly one). The anchor function is the resolver's own.
 */
export function recordReferenceExecAnchorRows(
  project: import('../../src/content/content.types').ProjectContent,
  anchorOf: (phase: import('../../src/content/content.types').PhaseContent, task: import('../../src/content/pack-compiler').CompiledTask) => string,
  soleTaskFor: (phase: import('../../src/content/content.types').PhaseContent) => import('../../src/content/pack-compiler').CompiledTask,
): ExecAnchorRow[] {
  return project.phases
    .filter((phase) => EXECUTABLE_KINDS.includes(phase.checks.kind))
    .map((phase) => ({ anchor: anchorOf(phase, soleTaskFor(phase)), grain: 'exec' as const, pack: project.slug, version: project.version, phaseKey: phase.key }));
}

/** The committed exec rows with the fresh ones: other versions' rows kept, this version's replaced. */
export function mergeReferenceExecAnchorRows(held: readonly ExecAnchorRow[], fresh: readonly ExecAnchorRow[]): ExecAnchorRow[] {
  const current = new Set(fresh.map((row) => `${row.pack}@${row.version}`));
  return [...held.filter((row) => !current.has(`${row.pack}@${row.version}`)), ...fresh];
}

export function renderReferenceExecAnchorsModule(rows: readonly ExecAnchorRow[]): string {
  const body = rows
    .map((row) => `  { anchor: '${row.anchor}', grain: '${row.grain}', pack: '${row.pack}', version: '${row.version}', phaseKey: '${row.phaseKey}' },`)
    .join('\n');
  return `/**
 * GENERATED by \`apps/api/test/cli/reference-anchors.ts --exec\`: do not edit by hand.
 *
 * The \`exec\` anchors of TaskTrackr's own executable phases.
 * \`project-scope.ts\` gives TaskTrackr's reviewer, mentor and Agentic prompts
 * to an executable phase only when its workspace is the reference application
 * and its one work task's anchor is here (the brief, objectives, rubric,
 * owned baselines, runs, mutants, hidden tests, reference answer, check slice
 * and mentor block), and the neutral prompts to every other one, an upload
 * first among them. A pack bump appends its rows and keeps the old ones; the
 * drift spec fails until the new rows are recorded on purpose.
 *
 * It is kept apart from \`reference-anchors.ts\` so that table, and its
 * \`--check\`, stay at the four written rows byte for byte. Like it, this is a
 * runtime file that imports nothing: the recorder lives under \`test/\`.
 */
export interface ReferenceExecAnchorRow {
  readonly anchor: string;
  readonly grain: 'exec';
  readonly pack: string;
  readonly version: string;
  readonly phaseKey: string;
}

export const REFERENCE_EXEC_ANCHORS: readonly ReferenceExecAnchorRow[] = [
${body}${rows.length ? '\n' : ''}];
`;
}

/** Parse the flags; null on bad usage. */
function parse(args: string[]): { check: boolean; exec: boolean; root: string | null } | null {
  let root: string | null = null;
  let check = false;
  let exec = false;
  for (let at = 0; at < args.length; at += 1) {
    const arg = args[at];
    if (arg === '--check') check = true;
    else if (arg === '--exec') exec = true;
    else if (arg === '--root') {
      const value = args[at + 1];
      if (!value || value.startsWith('--')) return null;
      root = path.resolve(value);
      at += 1;
    } else return null;
  }
  return { check, exec, root };
}

async function main(): Promise<number> {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) {
    process.stdout.write(USAGE);
    return 0;
  }
  const parsed = parse(args);
  if (!parsed) {
    process.stderr.write(`unknown or incomplete option: ${args.join(' ')}\n${USAGE}`);
    return 3;
  }
  const { check, exec, root } = parsed;
  if (exec && !check && !fs.existsSync(EXEC_TABLE)) {
    fs.writeFileSync(EXEC_TABLE, renderReferenceExecAnchorsModule([]), 'utf-8');
    const { spawnSync } = require('child_process') as typeof import('child_process');
    const again = spawnSync(process.execPath, [...process.execArgv, ...process.argv.slice(1)], { stdio: 'inherit' });
    return again.status ?? 1;
  }

  readSharedFromSource();
  const { Logger } = require('@nestjs/common') as typeof import('@nestjs/common');
  if (exec) return execMain(check, root ?? DEFAULT_ROOT, Logger);
  const { ContentService } = require('../../src/content/content.service') as typeof import('../../src/content/content.service');
  const table = require('../reference-anchor-table') as typeof Table;
  const { REFERENCE_ANCHORS } = require('../../src/assistant/reference-anchors') as typeof import('../../src/assistant/reference-anchors');
  Logger.overrideLogger(false);

  let content: InstanceType<typeof ContentService>;
  try {
    if (root) {
      const { DirectoryPackSource } = require('../../src/content/pack-source') as typeof import('../../src/content/pack-source');
      const project = new ContentService().loadProject(new DirectoryPackSource(root));
      if (project.slug !== table.ANCHORED_PACK) {
        process.stderr.write(`refused: ${root} holds the pack "${project.slug}", not the reference pack "${table.ANCHORED_PACK}"\n`);
        return 1;
      }
      content = { getProject: () => project } as unknown as InstanceType<typeof ContentService>;
    } else {
      content = new ContentService();
      content.loadAll();
    }
  } catch (err) {
    process.stderr.write(`${(err as Error).message}\n`);
    return 1;
  }

  const fresh = table.recordReferenceAnchorRows(content);
  const body = table.renderReferenceAnchorsModule(table.mergeReferenceAnchorRows(REFERENCE_ANCHORS, fresh));
  const label = `${table.ANCHORED_PACK} ${fresh[0]?.version ?? '?'}: ${fresh.length} anchors`;
  if (check) {
    const held = fs.existsSync(TABLE) ? fs.readFileSync(TABLE, 'utf-8') : '';
    const same = held === body;
    process.stdout.write(`${label} ${same ? 'match' : 'DIFFER FROM'} ${TABLE}\n`);
    return same ? 0 : 1;
  }
  fs.writeFileSync(TABLE, body, 'utf-8');
  process.stdout.write(`${label} -> ${TABLE}\n`);
  return 0;
}

/** `--exec`: the executable phases' rows, in their own file. */
function execMain(check: boolean, root: string, Logger: typeof import('@nestjs/common').Logger): number {
  const { ContentService } = require('../../src/content/content.service') as typeof import('../../src/content/content.service');
  const { DirectoryPackSource } = require('../../src/content/pack-source') as typeof import('../../src/content/pack-source');
  const { soleTaskFor } = require('../../src/content/pack-compiler') as typeof import('../../src/content/pack-compiler');
  Logger.overrideLogger(false);
  let project: import('../../src/content/content.types').ProjectContent;
  try {
    project = new ContentService().loadProject(new DirectoryPackSource(root));
  } catch (err) {
    process.stderr.write(`${(err as Error).message}\n`);
    return 1;
  }
  // Typed structurally, not by `typeof import(...)`: a type import would pull the
  // resolver (and the table it reads) into this file's compile before the
  // empty table above exists.
  const { executableReferenceAnchor } = require('../../src/assistant/project-scope') as {
    executableReferenceAnchor: (phase: import('../../src/content/content.types').PhaseContent, task: import('../../src/content/pack-compiler').CompiledTask) => string;
  };
  const held = fs.existsSync(EXEC_TABLE) ? (require('../../src/assistant/reference-exec-anchors') as { REFERENCE_EXEC_ANCHORS: readonly ExecAnchorRow[] }).REFERENCE_EXEC_ANCHORS : [];
  // The rows say "this is the reference's"; a root holding another pack must never be recorded as it.
  if (project.slug !== REFERENCE_PACK) {
    process.stderr.write(`refused: ${root} holds the pack "${project.slug}", not the reference pack "${REFERENCE_PACK}"\n`);
    return 1;
  }
  const fresh = recordReferenceExecAnchorRows(project, executableReferenceAnchor, soleTaskFor);
  const body = renderReferenceExecAnchorsModule(mergeReferenceExecAnchorRows(held, fresh));
  const label = `${project.slug} ${project.version}: ${fresh.length} exec anchors`;
  if (check) {
    const now = fs.existsSync(EXEC_TABLE) ? fs.readFileSync(EXEC_TABLE, 'utf-8') : '';
    const same = now === body;
    process.stdout.write(`${label} ${same ? 'match' : 'DIFFER FROM'} ${EXEC_TABLE}\n`);
    return same ? 0 : 1;
  }
  fs.writeFileSync(EXEC_TABLE, body, 'utf-8');
  process.stdout.write(`${label} -> ${EXEC_TABLE}\n`);
  return 0;
}

if (require.main === module) {
  main().then(
    (code) => process.exit(code),
    (err) => {
      process.stderr.write(`${(err as Error).stack ?? String(err)}\n`);
      process.exit(1);
    },
  );
}
