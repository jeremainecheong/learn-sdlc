import 'reflect-metadata';
import { createHash } from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { UPLOAD_PACKS_DIR } from '../fixtures/paths';
import { packFilesOf } from '../fixtures/upload-packs/archive';
import { readSharedFromSource } from './shared-from-source';

/**
 * Record the two staff downloads, the starter and the shelf example, into
 * `apps/api/src/authoring/starter-archive.generated.ts`. The generated module
 * is base64 of the deterministic stored zip the
 * export writes (`storedZipOf`, `src/authoring/export.service.ts`), one per
 * pack directory under `test/fixtures/upload-packs/`, and it imports nothing.
 *
 *   npx ts-node --project apps/api/tsconfig.json apps/api/test/cli/starter-archive.ts --write
 *   ... starter-archive.ts --check
 *
 * It lives under `test/`: a tool that writes source
 * must not ship in the image, and a `src/` file importing `test/` stops the
 * production build (TS6059). Only the server helper (`starter-archive.ts`) and
 * the generated module are in `src/`, and neither imports from `test/`.
 *
 * The bytes are a function of the fixture's bytes alone: names sorted
 * byte-wise, every header stamped `EXPORT_STAMP` (1980-01-01), stored, never
 * deflated. Recording is a deliberate act (a fixture edit, declared in the
 * change that makes it) and never the fix for a failing `--check`.
 *
 * Exit codes: 0 written (or matches under --check), 1 differs or a pack
 * directory is missing, 3 bad usage.
 */

/** The archives this module records, in the order the generated module lists them. */
export const STARTER_ARCHIVE_SOURCES = ['starter', 'shelf'] as const;
export type StarterArchiveSource = (typeof STARTER_ARCHIVE_SOURCES)[number];

const API_DIR = path.resolve(__dirname, '..', '..');
const DEFAULT_GENERATED = path.join(API_DIR, 'src', 'authoring', 'starter-archive.generated.ts');

/** The folder every entry sits in, and the name the download is saved as. */
export const archiveRootOf = (name: StarterArchiveSource): string => `learnsdlc-${name}`;
export const archiveFilenameOf = (name: StarterArchiveSource): string => `${archiveRootOf(name)}.zip`;

/** Base64 is written in lines this long, so no editor or diff meets one 200 KB line. */
const LINE = 120;

export interface RecordedArchive {
  name: StarterArchiveSource;
  filename: string;
  bytes: Buffer;
  sha256: string;
}

type StoredZipOf = (root: string, files: ReadonlyMap<string, Buffer>) => Buffer;

function storedZipWriter(): StoredZipOf {
  // Required here rather than imported at the top: the export service pulls the
  // whole authoring graph, and `--help` should not have to load it.
  return (require('../../src/authoring/export.service') as { storedZipOf: StoredZipOf }).storedZipOf;
}

/** One pack directory as the export writer zips it. */
export function archiveOf(name: StarterArchiveSource, fixturesDir: string = UPLOAD_PACKS_DIR): RecordedArchive {
  const dir = path.join(fixturesDir, name);
  if (!fs.existsSync(path.join(dir, 'project.json'))) {
    throw new Error(`no pack at test/fixtures/upload-packs/${name} (project.json is missing)`);
  }
  const files = new Map(packFilesOf(dir).map((file) => [file.name, file.data] as const));
  const bytes = storedZipWriter()(archiveRootOf(name), files);
  return { name, filename: archiveFilenameOf(name), bytes, sha256: createHash('sha256').update(bytes).digest('hex') };
}

export function archivesOf(fixturesDir: string = UPLOAD_PACKS_DIR): RecordedArchive[] {
  return STARTER_ARCHIVE_SOURCES.map((name) => archiveOf(name, fixturesDir));
}

/** The generated module's text: the one place the archive bytes live in `src/`. */
export function renderStarterArchiveModule(archives: readonly RecordedArchive[]): string {
  const out: string[] = [
    '// GENERATED by apps/api/test/cli/starter-archive.ts --write. Do not edit by hand:',
    '// change the pack under apps/api/test/fixtures/upload-packs/, then run the generator,',
    '// and `--check` holds the two together. It imports nothing.',
    '//',
    "// The staff downloads: each pack as the export's stored zip, base64. They",
    '// carry example hidden tests and solutions, so they are served to staff only, and',
    '// every download leaves an audit row.',
    '',
    'export interface StarterArchiveRecord {',
    '  readonly filename: string;',
    '  readonly size: number;',
    '  readonly sha256: string;',
    '  readonly base64: string;',
    '}',
    '',
    `export const STARTER_ARCHIVE_NAMES_GENERATED = [${archives.map((one) => `'${one.name}'`).join(', ')}] as const;`,
    '',
    'export const STARTER_ARCHIVE_RECORDS: Readonly<Record<(typeof STARTER_ARCHIVE_NAMES_GENERATED)[number], StarterArchiveRecord>> = {',
  ];
  for (const one of archives) {
    const base64 = one.bytes.toString('base64');
    out.push(`  ${one.name}: {`);
    out.push(`    filename: '${one.filename}',`);
    out.push(`    size: ${one.bytes.length},`);
    out.push(`    sha256: '${one.sha256}',`);
    out.push('    base64: [');
    for (let at = 0; at < base64.length; at += LINE) out.push(`      '${base64.slice(at, at + LINE)}',`);
    out.push("    ].join(''),");
    out.push('  },');
  }
  out.push('};', '');
  return out.join('\n');
}

const USAGE = `usage: ts-node test/cli/starter-archive.ts (--write | --check) [--fixtures <dir>] [--generated <file>]

  --write       write src/authoring/starter-archive.generated.ts from the packs
  --check       compare against the generated module and write nothing
  --fixtures    the directory holding starter/ and shelf/ (default test/fixtures/upload-packs)
  --generated   the generated module to write or check (default src/authoring/starter-archive.generated.ts)
  --help        print this
`;

interface Options {
  mode: 'write' | 'check';
  fixtures: string;
  generated: string;
}

function parse(args: readonly string[]): Options | null {
  let mode: Options['mode'] | null = null;
  let fixtures = UPLOAD_PACKS_DIR;
  let generated = DEFAULT_GENERATED;
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === '--write' || arg === '--check') {
      const next = arg === '--write' ? 'write' : 'check';
      if (mode && mode !== next) return null;
      mode = next;
    } else if (arg === '--fixtures' || arg === '--generated') {
      const value = args[i + 1];
      if (!value || value.startsWith('--')) return null;
      if (arg === '--fixtures') fixtures = path.resolve(value);
      else generated = path.resolve(value);
      i += 1;
    } else {
      return null;
    }
  }
  return mode ? { mode, fixtures, generated } : null;
}

/** Paths as the output prints them: relative to apps/api, never the machine's own. */
const shown = (at: string): string => {
  const rel = path.relative(API_DIR, at);
  return rel.startsWith('..') ? path.basename(at) : rel;
};

/** The CLI, callable from a spec: returns the exit code and never calls `process.exit`. */
export function main(args: readonly string[], write: (line: string) => void = (line) => process.stdout.write(line)): number {
  if (args.includes('--help') || args.includes('-h')) {
    write(USAGE);
    return 0;
  }
  const options = parse(args);
  if (!options) {
    write(`unknown or incomplete option\n${USAGE}`);
    return 3;
  }
  let archives: RecordedArchive[];
  try {
    archives = archivesOf(options.fixtures);
  } catch (error) {
    write(`${(error as Error).message}\n`);
    return 1;
  }
  const body = renderStarterArchiveModule(archives);
  const label = archives.map((one) => `${one.name} ${one.bytes.length} bytes`).join(', ');
  if (options.mode === 'check') {
    const held = fs.existsSync(options.generated) ? fs.readFileSync(options.generated, 'utf-8') : '';
    const same = held === body;
    write(`${label}: ${same ? 'match' : 'DIFFER FROM'} ${shown(options.generated)}\n`);
    return same ? 0 : 1;
  }
  fs.writeFileSync(options.generated, body, 'utf-8');
  write(`${label} -> ${shown(options.generated)}\n`);
  return 0;
}

if (require.main === module) {
  readSharedFromSource();
  const { Logger } = require('@nestjs/common') as typeof import('@nestjs/common');
  Logger.overrideLogger(false);
  process.exitCode = main(process.argv.slice(2));
}
