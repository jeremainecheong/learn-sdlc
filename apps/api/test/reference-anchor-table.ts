import type { ContentService } from '../src/content/content.service';
import { soleTaskFor } from '../src/content/pack-compiler';
import { phaseReferenceAnchor, referenceAnchor } from '../src/assistant/project-scope';
import type { ReferenceAnchorRow } from '../src/assistant/reference-anchors';

/**
 * The rows of `src/assistant/reference-anchors.ts`, recomputed from the pack on
 * disk, for reviewer scoping.
 *
 * One task-grain and one phase-grain anchor per **written** phase of
 * TaskTrackr (markdown, story or design) (an executable phase is reference
 * by the wall, not by an anchor). A design anchor is read only by the
 * screen-copy rule (`isReferenceTaskAnchor`): a design phase is never a
 * reference scope. The CLI writes the table from these rows; the drift spec holds
 * the committed table to them.
 */
export const ANCHORED_PACK = 'tasktrackr';

export function recordReferenceAnchorRows(content: ContentService): ReferenceAnchorRow[] {
  const project = content.getProject(ANCHORED_PACK);
  const rows: ReferenceAnchorRow[] = [];
  for (const phase of project.phases) {
    // written work: a story phase (Requirements since 3.0.0) or a design phase,
    // whose anchor only the screen-copy rule reads
    if (phase.checks.kind !== 'story' && phase.checks.kind !== 'design') continue;
    const task = soleTaskFor(phase);
    rows.push({ anchor: referenceAnchor(phase, task), grain: 'task', pack: ANCHORED_PACK, version: project.version, phaseKey: phase.key });
    rows.push({ anchor: phaseReferenceAnchor(phase, task), grain: 'phase', pack: ANCHORED_PACK, version: project.version, phaseKey: phase.key });
  }
  return rows;
}

/**
 * The committed table, rows of other versions kept (a pack bump appends
 * its rows; 2.0.1's stay), the current version's replaced, in a stable order.
 */
export function mergeReferenceAnchorRows(held: readonly ReferenceAnchorRow[], fresh: readonly ReferenceAnchorRow[]): ReferenceAnchorRow[] {
  const current = new Set(fresh.map((row) => `${row.pack}@${row.version}`));
  return [...held.filter((row) => !current.has(`${row.pack}@${row.version}`)), ...fresh];
}

export function renderReferenceAnchorsModule(rows: readonly ReferenceAnchorRow[]): string {
  const body = rows
    .map((row) => `  { anchor: '${row.anchor}', grain: '${row.grain}', pack: '${row.pack}', version: '${row.version}', phaseKey: '${row.phaseKey}' },`)
    .join('\n');
  return `/**
 * GENERATED by \`apps/api/test/cli/reference-anchors.ts\`: do not edit by hand.
 *
 * The byte anchors of TaskTrackr's own written tasks and phases, which scope
 * the reviewer. \`project-scope.ts\` gives TaskTrackr's reviewer, mentor and
 * Agentic prompts to a task or phase whose anchor is here, and the neutral
 * prompts to everything else. A pack bump appends its rows and keeps the old
 * ones (a copy of an older version is still TaskTrackr's content); the drift
 * spec fails until the new rows are recorded on purpose.
 *
 * This is the only runtime file of the anchor machinery, and it imports
 * nothing: the recorder lives under \`test/\` and never ships in the image.
 */
export interface ReferenceAnchorRow {
  readonly anchor: string;
  readonly grain: 'task' | 'phase';
  readonly pack: string;
  readonly version: string;
  readonly phaseKey: string;
}

export const REFERENCE_ANCHORS: readonly ReferenceAnchorRow[] = [
${body}
];
`;
}
